"""
Класифікація організацій для SWIFT-платежів.

Для «внутрішніх» організацій поява SWIFT не є подією: повідомлення завжди
йде як списання коштів (з коментарем), незалежно від HasSwift. Тому цей
перелік потрібен і при синхронізації (щоб не створювати дубль-запис при
появі свіфта), і при формуванні повідомлення.
"""

INTERNAL_ORG_CODES = {
    "00000001",  # ФТП
    "00000007",  # Жуков М.І., ФОП
    "00000008",  # Цвілій В.А., ФОП
    "00000009",  # Ветров В.А., ФОП
    "00000015",  # Окулов Є.В., ФОП
    "00000019",  # Панько О.І., ФОП
    "00000022",  # Василенко І.В., ФОП
    "00000023",  # Євтушенко К.В., ФОП
    "00000026",  # МО ЄПС, ТОВ
    "00000027",  # Окулов К.В., ФОП
    "00000028",  # Ступа О.Ю., ФОП
    "00000035",  # МРІЯ ТЕРМІНАЛ ТОВ
}


def normalize_org_code(value):
    """Код організації до вигляду '00000001' (PBI може віддати 1 або '1')."""
    if value is None:
        return None
    s = str(value).strip()
    if not s:
        return None
    return s.zfill(8) if s.isdigit() else s


def is_internal_org(value) -> bool:
    """Чи належить код організації до внутрішніх."""
    return normalize_org_code(value) in INTERNAL_ORG_CODES
